-- 1. TABLES

CREATE TABLE USERS (
    ID          NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USERNAME    VARCHAR2(150)  NOT NULL UNIQUE,
    EMAIL       VARCHAR2(200),
    PASSWORD    VARCHAR2(255)  NOT NULL,
    ROLE        VARCHAR2(20)   DEFAULT 'admin',
    CREATED_AT  DATE           DEFAULT SYSDATE
);

CREATE TABLE SESSIONS (
    ID          NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TOKEN       VARCHAR2(255)  NOT NULL UNIQUE,
    USER_ID     NUMBER         NOT NULL REFERENCES USERS(ID),
    EXPIRES_AT  TIMESTAMP      NOT NULL
);

CREATE TABLE CATEGORIES (
    ID          NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NAME        VARCHAR2(150)  NOT NULL,
    ICON        VARCHAR2(50)   DEFAULT 'fa-tag',
    DESCRIPTION VARCHAR2(500)
);

CREATE TABLE SUPPLIERS (
    ID          NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NAME        VARCHAR2(150)  NOT NULL,
    EMAIL       VARCHAR2(200),
    PHONE       VARCHAR2(30),
    ADDRESS     VARCHAR2(300)
);

CREATE TABLE PRODUCTS (
    ID          NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NAME        VARCHAR2(200)  NOT NULL,
    REF         VARCHAR2(50)   NOT NULL UNIQUE,
    CATEGORY_ID NUMBER         REFERENCES CATEGORIES(ID),
    SUPPLIER_ID NUMBER         REFERENCES SUPPLIERS(ID),
    PRICE       NUMBER(12,2)   NOT NULL,
    STOCK       NUMBER(10)     DEFAULT 0,
    SEUIL       NUMBER(10)     DEFAULT 10,
    LOCATION    VARCHAR2(100),
    DESCRIPTION VARCHAR2(1000),
    CREATED_AT  DATE           DEFAULT SYSDATE
);

CREATE TABLE MOVEMENTS (
    ID          NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PRODUCT_ID  NUMBER         NOT NULL REFERENCES PRODUCTS(ID),
    TYPE        VARCHAR2(10)   NOT NULL CHECK (TYPE IN ('in', 'out', 'adjust')),
    QUANTITY    NUMBER(10)     NOT NULL,
    NOTE        VARCHAR2(500),
    CREATED_BY  VARCHAR2(100),
    CREATED_AT  DATE           DEFAULT SYSDATE
);

CREATE TABLE INVENTORY (
    ID           NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PRODUCT_ID   NUMBER        NOT NULL REFERENCES PRODUCTS(ID),
    SYSTEM_QTY   NUMBER(10),
    PHYSICAL_QTY NUMBER(10),
    STATUS       VARCHAR2(20),
    NOTE         VARCHAR2(500),
    CREATED_AT   DATE          DEFAULT SYSDATE
);